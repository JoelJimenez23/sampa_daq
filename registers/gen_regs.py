#!/usr/bin/env python3
"""Generate the C register tables.

Sources (the generated .c tables are never edited by hand):

  <registers>/globreg.csv  -> SAMPA global registers
  <registers>/chreg.csv    -> SAMPA channel registers
  <registers>/fpga_regs.csv -> configurable FPGA fields (CNC and DM)

Usage:
  python3 registers/gen_regs.py [CSV_DIR] [OUT_DIR]

Both default to sensible values, so `make regs` is the normal way to run it.
Writes sampa_regs.c and fpga_regs.c into OUT_DIR (default sampa_cfg/).
"""
import csv
import os
import sys


def load_sampa(path):
    """Read the CSV files that come from the Windows GUI.

    Rows with compound==2 are bit sub-fields: they are skipped, exactly as
    Form1.cs does when it builds its own register lists.
    """
    out = []
    with open(path, newline='', encoding='utf-8-sig') as f:
        for cols in csv.reader(f, delimiter=';'):
            if len(cols) < 8 or cols[0].strip() == '':
                continue                       # cabecera o linea vacia
            if cols[5].strip() == '2':
                continue                       # sub-campo de bits
            out.append({
                'name': cols[0].strip(),
                'size': int(cols[1]),
                'addr': int(cols[3], 16),
                'ro':   cols[4].strip().upper() == 'TRUE',
                'desc': cols[7].strip().replace('"', "'"),
            })
    return out


def load_fpga(path):
    out = []
    with open(path, newline='', encoding='utf-8-sig') as f:
        for cols in csv.reader(f, delimiter=';'):
            if not cols or cols[0].strip().startswith('#'):
                continue
            if len(cols) < 7 or cols[0].strip() in ('', 'block', 'bloque'):
                continue
            out.append({
                'block': cols[0].strip(),
                'name':  cols[1].strip(),
                'reg':   int(cols[2], 0),
                'pos':   int(cols[3], 0),
                'bits':  int(cols[4], 0),
                'ro':    cols[5].strip().upper() == 'TRUE',
                'desc':  cols[6].strip().replace('"', "'"),
            })
    return out


HEADER = ('/* AUTOMATICALLY GENERATED by gen_regs.py -- do not edit by hand.\n'
          ' * To regenerate:  make regs\n'
          ' * Source: %s */\n')

LOOKUP = '''
#include <string.h>

static const %(type)s *find(const %(type)s *t, size_t n, const char *name)
{
  size_t i;
  for (i = 0; i < n; i++)
    if (strcasecmp(t[i].name, name) == 0)
      return &t[i];
  return NULL;
}
'''


def emit_sampa(rows, name, fh):
    fh.write("const sampa_reg_t %s[] = {\n" % name)
    for r in rows:
        fh.write('  { "%s", 0x%02X, %2d, %d, "%s" },\n'
                 % (r['name'], r['addr'], r['size'], 1 if r['ro'] else 0, r['desc']))
    fh.write("};\n")
    fh.write("const size_t %s_count = %d;\n\n" % (name, len(rows)))


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    res = sys.argv[1] if len(sys.argv) > 1 else here
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        os.path.dirname(here), 'sampa_cfg')

    # ---- SAMPA -------------------------------------------------------------
    glb = load_sampa(os.path.join(res, 'globreg.csv'))
    ch = load_sampa(os.path.join(res, 'chreg.csv'))
    with open(os.path.join(out, 'sampa_regs.c'), 'w') as fh:
        fh.write(HEADER % 'globreg.csv y chreg.csv')
        fh.write('#include "sampa_regs.h"\n\n')
        emit_sampa(glb, 'sampa_glb_regs', fh)
        emit_sampa(ch, 'sampa_ch_regs', fh)
        fh.write(LOOKUP % {'type': 'sampa_reg_t'})
        fh.write('''
const sampa_reg_t *sampa_find_glb(const char *name)
{
  return find(sampa_glb_regs, sampa_glb_regs_count, name);
}

const sampa_reg_t *sampa_find_ch(const char *name)
{
  return find(sampa_ch_regs, sampa_ch_regs_count, name);
}
''')

    # ---- FPGA --------------------------------------------------------------
    fpga = load_fpga(os.path.join(res, 'fpga_regs.csv'))
    with open(os.path.join(out, 'fpga_regs.c'), 'w') as fh:
        fh.write(HEADER % 'fpga_regs.csv')
        fh.write('#include "fpga_regs.h"\n\n')
        fh.write("const fpga_field_t fpga_fields[] = {\n")
        for r in fpga:
            fh.write('  { "%s", "%s", %2d, %2d, %2d, %d, "%s" },\n'
                     % (r['block'], r['name'], r['reg'], r['pos'], r['bits'],
                        1 if r['ro'] else 0, r['desc']))
        fh.write("};\n")
        fh.write("const size_t fpga_fields_count = %d;\n" % len(fpga))
        fh.write('''
#include <string.h>

const fpga_field_t *fpga_find(const char *block, const char *name)
{
  size_t i;
  for (i = 0; i < fpga_fields_count; i++)
    if (strcasecmp(fpga_fields[i].block, block) == 0 &&
        strcasecmp(fpga_fields[i].name, name) == 0)
      return &fpga_fields[i];
  return NULL;
}
''')

    sys.stderr.write("generated: sampa_regs.c (%d global, %d channel), "
                     "fpga_regs.c (%d fields)\n" % (len(glb), len(ch), len(fpga)))


if __name__ == '__main__':
    main()
